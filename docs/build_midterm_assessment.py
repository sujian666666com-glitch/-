    doc = Document(str(TEMPLATE))
    table = doc.tables[0]

    set_cell_text(table.cell(0, 1), "赵庆")
    set_cell_text(table.cell(0, 3), "人工智能1班")
    set_cell_text(table.cell(0, 5), "陈金山")

